/// <reference types="node" />
// Generates src/content/days.generated.ts (a static require() for every day file),
// src/content/culture.generated.ts (every culture chapter + the photo file names) and
// src/content/culture-images.generated.ts (the photo requires, imported only by the app: Node cannot require
// a .jpg), so Metro can bundle them. Run after adding or removing a day, chapter or photo.
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(__dirname, '..');
const NL = '\n';
const list = (dir: string, re: RegExp) =>
  existsSync(join(root, dir))
    ? readdirSync(join(root, dir))
        .filter((f) => re.test(f))
        .sort()
    : [];
const HEAD = '// Generated by scripts/content-index.ts. Do not edit by hand.';

const files = list('content/days', /^day\d{2}\.json$/);
writeFileSync(
  join(root, 'src/content/days.generated.ts'),
  [HEAD, 'export const RAW_DAYS: unknown[] = [', ...files.map((f) => `  require('../../content/days/${f}'),`), '];', ''].join(NL),
);

const chapters = list('content/culture', /^[a-z0-9-]+\.json$/);
const photos = list('assets/culture', /^[a-z0-9-]+\.jpg$/);
const realLife = list('assets/real-life', /^day\d{2}\.jpg$/);
const scenes = list('assets/scenes', /^[a-z0-9-]+\.jpg$/);
writeFileSync(
  join(root, 'src/content/culture.generated.ts'),
  [
    HEAD,
    'export const RAW_CULTURE: unknown[] = [',
    ...chapters.map((f) => `  require('../../content/culture/${f}'),`),
    '];',
    '',
    '/** File names in assets/culture (plain strings, so Node scripts can check them). */',
    'export const CULTURE_PHOTO_FILES: string[] = [',
    ...photos.map((f) => `  '${f}',`),
    '];',
    '',
  ].join(NL),
);
writeFileSync(
  join(root, 'src/content/culture-images.generated.ts'),
  [
    HEAD,
    '/** Bundled culture photos (assets/culture), keyed by file name. */',
    'export const CULTURE_IMAGES: Record<string, number> = {',
    ...photos.map((f) => `  '${f}': require('../../assets/culture/${f}'),`),
    '};',
    '/** Bundled "In real life" photos (assets/real-life), one per day, keyed by file name. */',
    'export const REAL_LIFE_IMAGES: Record<string, number> = {',
    ...realLife.map((f) => `  '${f}': require('../../assets/real-life/${f}'),`),
    '};',
    '/** Bundled scenario scene photos (assets/scenes), one per scenario, keyed by file name. */',
    'export const SCENE_IMAGES: Record<string, number> = {',
    ...scenes.map((f) => `  '${f}': require('../../assets/scenes/${f}'),`),
    '};',
    '',
  ].join(NL),
);
console.log(
  `content:index: ${files.length} day files, ${chapters.length} culture chapters, ${photos.length} culture photos, ` +
    `${realLife.length} real-life photos, ${scenes.length} scene photos`,
);
