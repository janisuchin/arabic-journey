/// <reference types="node" />
// Generates src/content/days.generated.ts with a static require() for every day file,
// so Metro can bundle the lessons. Run after adding or removing a day file.
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(__dirname, '..');
const files = readdirSync(join(root, 'content/days'))
  .filter((f) => /^day\d{2}\.json$/.test(f))
  .sort();
const lines = files.map((f) => `  require('../../content/days/${f}'),`);
const src = `// Generated by scripts/content-index.ts. Do not edit by hand.
export const RAW_DAYS: unknown[] = [
${lines.join('\n')}
];
`;
writeFileSync(join(root, 'src/content/days.generated.ts'), src);
console.log(`content:index: ${files.length} day files`);
